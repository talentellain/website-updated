export function generateSEOContent(serviceSlug, citySlug) {
  const city = citiesData[citySlug.toLowerCase()];
  const service = servicesDataMap[serviceSlug.toLowerCase()];

  if (!city || !service) return null;

  const cityName = city.name;
  const serviceTitle = service.title;
  const servicePrice = service.price;

  // Render dynamic values with targeted SEO keywords
  const isMarketing = serviceTitle.includes('Marketing') || serviceTitle.includes('SEO') || serviceTitle.includes('Branding');
  const term = isMarketing ? 'Agency' : 'Company';
  const title = `${serviceTitle} ${term} in ${cityName}, Jharkhand | TalentElla`;
  const metaDescription = `Looking for a top ${serviceTitle.toLowerCase()} ${term.toLowerCase()} near me in ${cityName}, Jharkhand? TalentElla offers expert ${serviceTitle.toLowerCase()} services. Packages start at ${servicePrice}.`;
  
  const heroTagline = `${service.tagline} in ${cityName}`;
  
  const whyChooseUs = `Choosing TalentElla in ${cityName} means partnering with an agency that understands the local market. ${city.description} As a result, businesses require highly specialized strategies. ${city.hook} Our team builds responsive architectures, optimized campaigns, and brand systems that address the unique needs of ${city.industryFocus} across Jharkhand.`;

  const dynamicFaqs = service.faqs.map(f => {
    return {
      question: f.question.replace(/\[City\]/g, cityName),
      answer: f.answer.replace(/\[City\]/g, cityName)
    };
  });

  return {
    cityName,
    serviceTitle,
    servicePrice,
    title,
    metaDescription,
    heroTagline,
    whyChooseUs,
    faqs: dynamicFaqs,
    industries: city.industries,
    serviceId: service.serviceId,
    serviceDescription: service.description
  };
}
